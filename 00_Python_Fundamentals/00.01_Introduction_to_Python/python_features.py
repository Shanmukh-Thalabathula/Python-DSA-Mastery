"""
Demonstrates some beginner-friendly Python features.
"""

# Dynamic typing
language = "Python"
version = 3.12

print(language)
print(version)

# Arithmetic
print(10 + 20)

# String repetition
print("=" * 30)

# Lists
numbers = [10, 20, 30]

print(numbers)

# Loop
for number in numbers:
    print(number)